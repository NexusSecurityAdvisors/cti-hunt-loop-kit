#!/usr/bin/env python3
"""
Build the ATT&CK Navigator coverage layer for the CTI Hunt Loop Kit from the Sigma rules.

Every ATT&CK technique tag (attack.tNNNN[.NNN]) on a rule in queries/sigma counts as coverage by
that rule's playbook. The score is the number of playbooks that hunt the technique.

    python tools/build_navigator_layer.py           # write navigator/cti-hunt-loop-kit.layer.json + COVERAGE.md
    python tools/build_navigator_layer.py --check   # exit 1 if the committed files are stale (used in CI)

Standard library plus PyYAML (installed with sigma-cli).
"""
import json
import re
import sys
from collections import defaultdict
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "navigator"
REPO = "https://github.com/NexusSecurityAdvisors/cti-hunt-loop-kit/blob/main"
ATTACK_VERSION = "20"
TACTIC_ORDER = ["reconnaissance", "resource-development", "initial-access", "execution", "persistence",
                "privilege-escalation", "stealth", "defense-impairment", "credential-access", "discovery",
                "lateral-movement", "collection", "command-and-control", "exfiltration", "impact"]


def load_rules():
    rules = []
    for path in sorted((ROOT / "queries" / "sigma").glob("hl-*.yml")):
        hunt = "HL-" + re.match(r"hl-(\d{4})", path.name).group(1)
        docs = [d for d in yaml.safe_load_all(path.read_text()) if d and "logsource" in d]
        tags = {t for d in docs for t in d.get("tags", [])}
        playbook = next((ROOT / "playbooks").glob(f"{hunt}-*.md"))
        title = re.sub(r"^#\s*Playbook\s+HL-\d{4}\s*[—-]\s*", "", playbook.read_text().splitlines()[0]).strip()
        rules.append(dict(
            hunt=hunt, title=title, playbook=f"playbooks/{playbook.name}",
            techniques=sorted(t[len("attack."):].upper() for t in tags if re.fullmatch(r"attack\.t\d{4}(\.\d{3})?", t)),
            tactics=sorted(t[len("attack."):] for t in tags if t[len("attack."):] in TACTIC_ORDER)))
    return rules


def build(rules):
    by_tech = defaultdict(list)
    for r in rules:
        for t in r["techniques"]:
            by_tech[t].append(r)
    max_score = max(len(v) for v in by_tech.values())
    techniques = []
    for tid in sorted(by_tech):
        hunts = by_tech[tid]
        techniques.append({
            "techniqueID": tid,
            "score": len(hunts),
            "color": "",
            "comment": "; ".join(f"{h['hunt']} {h['title']}" for h in hunts),
            "enabled": True,
            "metadata": [{"name": "Playbook", "value": h["hunt"]} for h in hunts],
            "links": [{"label": h["hunt"], "url": f"{REPO}/{h['playbook']}"} for h in hunts],
            "showSubtechniques": False,
        })
    layer = {
        "name": "CTI Hunt Loop Kit coverage",
        "versions": {"attack": ATTACK_VERSION, "navigator": "5.1.0", "layer": "4.5"},
        "domain": "enterprise-attack",
        "description": f"Techniques hunted by the CTI Hunt Loop Kit playbooks ({len(rules)} playbooks). "
                       f"Score = number of playbooks hunting the technique. Generated by tools/build_navigator_layer.py.",
        "filters": {"platforms": ["Windows", "Linux", "Identity Provider", "Office Suite", "SaaS", "Network Devices"]},
        "sorting": 3,
        "layout": {"layout": "side", "aggregateFunction": "max", "showID": True, "showName": True,
                   "showAggregateScores": False, "countUnscored": False, "expandedSubtechniques": "annotated"},
        "hideDisabled": False,
        "techniques": techniques,
        "gradient": {"colors": ["#c6dbef", "#08519c"], "minValue": 1, "maxValue": max(max_score, 2)},
        "legendItems": [{"label": "Hunted by 1 playbook", "color": "#c6dbef"},
                        {"label": f"Hunted by {max(max_score, 2)}+ playbooks", "color": "#08519c"}],
        "metadata": [{"name": "Source", "value": "https://github.com/NexusSecurityAdvisors/cti-hunt-loop-kit"}],
        "links": [], "showTacticRowBackground": False, "tacticRowBackground": "#dddddd",
        "selectTechniquesAcrossTactics": True, "selectSubtechniquesWithParent": False, "selectVisibleTechniques": False,
    }

    tactic_rows = defaultdict(list)
    for r in rules:
        for tac in r["tactics"]:
            tactic_rows[tac].append(r["hunt"])
    lines = [
        "# ATT&CK coverage",
        "",
        "_Generated by `tools/build_navigator_layer.py` from the Sigma rule tags. Do not edit by hand._",
        "",
        f"**{len(rules)} playbooks · {len(by_tech)} techniques and sub-techniques · ATT&CK v{ATTACK_VERSION}**",
        "",
        "Open the interactive view in the [ATT&CK Navigator](https://mitre-attack.github.io/attack-navigator/): "
        "*Open Existing Layer → Upload from local* and choose [`cti-hunt-loop-kit.layer.json`](cti-hunt-loop-kit.layer.json), "
        "or *Load from URL* with the file's raw GitHub URL.",
        "",
        "## By tactic",
        "",
        "| Tactic | Playbooks |",
        "|---|---|",
    ]
    for tac in TACTIC_ORDER:
        if tac in tactic_rows:
            name = tac.replace("-", " ").title().replace("And", "and")
            lines.append(f"| {name} | {', '.join(sorted(set(tactic_rows[tac])))} |")
    lines += ["", "## By technique", "", "| Technique | Playbooks |", "|---|---|"]
    for tid in sorted(by_tech):
        hunts = ", ".join(f"[{h['hunt']}](../{h['playbook']})" for h in by_tech[tid])
        lines.append(f"| [{tid}](https://attack.mitre.org/techniques/{tid.replace('.', '/')}/) | {hunts} |")
    lines += ["", "## Gaps worth hunting next", "",
              "Tactics with no playbook yet: " +
              ", ".join(t.replace("-", " ") for t in TACTIC_ORDER if t not in tactic_rows) + ".", ""]
    return json.dumps(layer, indent=2) + "\n", "\n".join(lines)


def main():
    layer, md = build(load_rules())
    targets = {OUT / "cti-hunt-loop-kit.layer.json": layer, OUT / "COVERAGE.md": md}
    if "--check" in sys.argv:
        stale = [str(p.relative_to(ROOT)) for p, c in targets.items() if not p.exists() or p.read_text() != c]
        if stale:
            sys.exit(f"Stale: {', '.join(stale)}. Run python tools/build_navigator_layer.py and commit the result.")
        print("Navigator layer is up to date.")
        return
    OUT.mkdir(exist_ok=True)
    for p, c in targets.items():
        p.write_text(c)
        print(f"wrote {p.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
